import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const overlaySource = readFileSync(fileURLToPath(new URL('../src/components/dramaCanvas/CanvasNodeStatusOverlay.vue', import.meta.url)), 'utf8')
const canvasSource = readFileSync(fileURLToPath(new URL('../src/views/DramaCanvas.vue', import.meta.url)), 'utf8')

test('节点状态覆盖层提供结果、提示词和失败原因操作', () => {
  assert.match(overlaySource, /打开结果/)
  assert.match(overlaySource, /复制链接/)
  assert.match(overlaySource, /下载结果/)
  assert.match(overlaySource, /存入素材库/)
  assert.match(overlaySource, /复制素材引用/)
  assert.match(overlaySource, /failedHint/)
  assert.match(overlaySource, /可点击重试继续执行/)
  assert.match(overlaySource, /queueLabel/)
  assert.match(overlaySource, /步骤 \$\{status\.value\.stepIndex\}\/\$\{status\.value\.stepTotal\}/)
  assert.match(overlaySource, /已恢复中断状态/)
  assert.match(overlaySource, /已恢复运行状态/)
  assert.match(overlaySource, /设为本镜图/)
  assert.match(overlaySource, /设为首帧/)
  assert.match(overlaySource, /设为尾帧/)
  assert.match(overlaySource, /设为本镜视频/)
  assert.match(overlaySource, /设为本镜音频/)
  assert.match(overlaySource, /复制提示词/)
  assert.match(overlaySource, /复制原因/)
  assert.match(overlaySource, /class="result-preview"/)
  assert.match(overlaySource, /<img v-if="resultPreviewType === 'image'"/)
  assert.match(overlaySource, /<video v-else-if="resultPreviewType === 'video'"/)
  assert.match(overlaySource, /<audio v-else-if="resultPreviewType === 'audio'"/)
  assert.match(overlaySource, /function copyPrompt\(\)/)
  assert.match(overlaySource, /function copyResultLink\(\)/)
  assert.match(overlaySource, /function downloadResult\(\)/)
  assert.match(overlaySource, /link\.download = resultFilename\(\)/)
  assert.match(overlaySource, /assetsAPI\.create\(\{/)
  assert.match(overlaySource, /category: 'canvas-result'/)
  assert.match(overlaySource, /source: 'canvas_node_result'/)
  assert.match(overlaySource, /function saveResultAsset\(\)/)
  assert.match(overlaySource, /savedAsset\.value = asset \|\| null/)
  assert.match(overlaySource, /function copyAssetReference\(\)/)
  assert.match(overlaySource, /@素材\(\$\{name\}#\$\{savedAsset\.value\.id\}\)/)
  assert.match(overlaySource, /function attachImageResult\(slot = 'main'\)/)
  assert.match(overlaySource, /imagesAPI\.upload\(\{/)
  assert.match(overlaySource, /frame_type: slot === 'first' \? 'storyboard_first' : slot === 'last' \? 'storyboard_last' : undefined/)
  assert.match(overlaySource, /function attachVideoResult\(\)/)
  assert.match(overlaySource, /videosAPI\.attach\(\{/)
  assert.match(overlaySource, /function attachAudioResult\(\)/)
  assert.match(overlaySource, /storyboardsAPI\.update\(storyboardId, \{ audio_local_path: localPath \}\)/)
  assert.match(overlaySource, /function copyError\(\)/)
})

test('画布节点运行状态会携带当前节点提示词', () => {
  assert.match(canvasSource, /function nodeStepPromptText\(step, sb, node\)/)
  assert.match(canvasSource, /nodeStatus\.set\(nodeId, \{ step, message: statusMessage, promptText/)
  assert.match(canvasSource, /const resultInfo = \{ \.\.\.nodeStepResultInfo\(node, step, sb\.id\), promptText \}/)
  assert.match(canvasSource, /errorDetail: errorMessage/)
})
